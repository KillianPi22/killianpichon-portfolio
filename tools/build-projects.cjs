/* Generate HTML from the existing React components, offline. No browser, server or secrets. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const pages = require('../assets/project-pages.js');
const read = file => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n');
const escape = text => String(text || '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
const json = value => JSON.stringify(value).replace(/</g, '\\u003c');
const marker = '<!-- Generated by tools/build-projects.cjs. Edit index.html or data/, then rebuild. -->';
const index = read('index.html');
const scripts = [...index.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)];
const reactScript = scripts.find(m => m[2].includes('react.production.min.js'));
const domScript = scripts.find(m => m[2].includes('react-dom.production.min.js'));
const appScript = scripts.find(m => m[2].includes('function App()'));
const style = index.match(/<style>([\s\S]*?)<\/style>/);
if (!reactScript || !domScript || !appScript || !style) throw new Error('Portfolio template structure changed; review the builder.');
const serverRenderer = fs.readFileSync(path.join(path.dirname(require.resolve('react-dom/package.json')), 'umd/react-dom-server-legacy.browser.production.min.js'), 'utf8');
if (process.argv.includes('--verify-dependencies')) process.exit(0);
const homeSchema = JSON.parse(scripts.find(m => /application\/ld\+json/.test(m[1]))[2]);
const dataContext = { window: {} };
for (const file of ['data/projects.js', 'data/fr.js']) vm.runInNewContext(read(file), dataContext, { filename: file });
const projects = dataContext.window.KP_PROJECTS;
const french = dataContext.window.KP_FR;
const ids = Object.keys(projects).filter(id => pages.isPublic(projects[id]));
const outputs = new Map();
outputs.set('assets/project-base.css', '/* Generated from index.html by tools/build-projects.cjs. */\n' + style[1].trim() + '\n');
outputs.set('assets/portfolio-vendor.js', '/* Generated from the existing inline React libraries. */\n' + reactScript[2].trimEnd() + '\n' + domScript[2].trimEnd() + '\n');
outputs.set('assets/portfolio-app.js', '/* Generated from index.html by tools/build-projects.cjs. */\n' + appScript[2] + '\n');

function render(id, lang) {
  const location = new URL(pages.origin + pages.path(id, lang));
  const context = { URL, URLSearchParams, console, setTimeout, clearTimeout };
  context.window = context;
  context.self = context;
  context.location = location;
  context.navigator = { language: lang };
  context.localStorage = { getItem: () => null };
  context.document = {
    baseURI: pages.origin,
    documentElement: { setAttribute() {} },
    addEventListener() {},
    querySelector: selector => selector === 'base' ? { setAttribute() {} } : null,
    getElementById: () => null
  };
  // All hooks run through React's real static renderer. Effects do not execute.
  context.ReactDOM = { createRoot: () => ({ render() {} }) };
  vm.createContext(context);
  vm.runInContext(reactScript[2], context);
  vm.runInContext(serverRenderer, context);
  for (const script of scripts) {
    if (/application\/ld\+json|\bdefer\b/.test(script[1]) || script === reactScript || script === domScript) continue;
    const src = script[1].match(/\bsrc="([^"]+)"/);
    vm.runInContext(src ? read(src[1].split('?')[0]) : script[2], context, { filename: src ? src[1] : 'portfolio-inline.js' });
  }
  return vm.runInContext('ReactDOMServer.renderToString(React.createElement(App))', context);
}

function replaceAttribute(html, selector, value) {
  const pattern = new RegExp('(<(?:meta|link) ' + selector + '[^>]*?)(content|href)="[^"]*"');
  if (!pattern.test(html)) throw new Error('Missing metadata: ' + selector);
  return html.replace(pattern, (_, before, attribute) => before + attribute + '="' + escape(value) + '"');
}
const manifestFile = 'data/project-pages-manifest.json';
const previous = fs.existsSync(path.join(root, manifestFile)) ? JSON.parse(read(manifestFile)) : { pages: {} };
const manifest = { version: 1, pages: {} };
for (const id of ids) {
  for (const lang of ['en', 'fr']) {
    const project = Object.assign({}, projects[id], lang === 'fr' ? french.projects[id] : {});
    const meta = pages.meta(id, project, lang);
    const route = pages.path(id, lang);
    const canonical = pages.origin + route;
    let html = index.replace('<!doctype html>', '<!doctype html>\n' + marker)
      .replace('<html lang="en">', '<html lang="' + (lang === 'fr' ? 'fr-CA' : 'en') + '">')
      .replace('<base href="./">', '<base href="' + '../'.repeat(route.split('/').filter(Boolean).length) + '">')
      .replace(/<title>[\s\S]*?<\/title>/, () => '<title>' + escape(meta.title) + '</title>')
      .replace(style[0], '<link rel="stylesheet" href="assets/project-base.css?v=20261030-avatar">')
      .replace(/<body>[\s\S]*?(?=<script>\/\*\*)/, () => '<body>\n  <div id="root">' + render(id, lang) + '</div>\n  ')
      .replace(reactScript[0], '<script src="assets/portfolio-vendor.js?v=20261030-projects"></script>')
      .replace(domScript[0], '')
      .replace(appScript[0], () => '<script>window.KP_HOME_SCHEMA=' + json(homeSchema) + ';</script>\n<script src="assets/portfolio-app.js?v=20261031-native"></script>')
      .replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>/, () => '<script type="application/ld+json">' + json(pages.graph(id, project, lang)) + '</script>')
      .replace(/\s*<meta property="og:image:(?:width|height|type)"[^>]*>/g, '');
    for (const [selector, value] of [
      ['name="description"', meta.description], ['rel="canonical"', canonical],
      ['property="og:title"', meta.title], ['property="og:description"', meta.description], ['property="og:url"', canonical],
      ['property="og:locale"', lang === 'fr' ? 'fr_CA' : 'en_CA'], ['property="og:image"', meta.image], ['property="og:image:alt"', meta.imageAlt],
      ['name="twitter:title"', meta.title], ['name="twitter:description"', meta.description], ['name="twitter:image"', meta.image], ['name="twitter:image:alt"', meta.imageAlt],
      ['rel="alternate" hreflang="en"', pages.origin + pages.path(id, 'en')],
      ['rel="alternate" hreflang="fr-CA"', pages.origin + pages.path(id, 'fr')],
      ['rel="alternate" hreflang="x-default"', pages.origin + pages.path(id, 'en')]
    ]) html = replaceAttribute(html, selector, value);
    html = html.replace(/[\t ]+$/gm, '');
    const file = route + 'index.html';
    const digest = crypto.createHash('sha256').update(html).digest('hex');
    const lastmod = previous.pages[file]?.digest === digest ? previous.pages[file].lastmod : new Date().toISOString().slice(0, 10);
    manifest.pages[file] = { digest, lastmod };
    outputs.set(file, html);
  }
}

const start = '<!-- public-projects:start -->', end = '<!-- public-projects:end -->';
let sitemap = read('sitemap.xml');
const allImages = ['assets/og-image.jpg', ...new Set(ids.flatMap(id => [projects[id].thumb, projects[id].heroImage, ...(projects[id].galleryImages || [])].filter(pages.publicImage)))];
sitemap = sitemap.replace(/<url>[\s\S]*?<\/url>/, block => {
  const imageXML = allImages.map(image => '    <image:image>\n      <image:loc>' + escape(pages.origin + image) + '</image:loc>\n    </image:image>').join('\n');
  return block.replace(/\s*<image:image>[\s\S]*?<\/image:image>/g, '').replace(/\s*<\/url>/, '\n' + imageXML + '\n  </url>');
});
const entries = [];
for (const id of ids) {
  const images = [...new Set([projects[id].thumb, projects[id].heroImage, ...(projects[id].galleryImages || [])].filter(pages.publicImage))];
  for (const lang of ['en', 'fr']) {
    const route = pages.path(id, lang);
    entries.push('  <url>\n    <loc>' + pages.origin + route + '</loc>\n    <lastmod>' + manifest.pages[route + 'index.html'].lastmod + '</lastmod>\n' +
      [['en', 'en'], ['fr-CA', 'fr'], ['x-default', 'en']].map(([label, language]) => '    <xhtml:link rel="alternate" hreflang="' + label + '" href="' + pages.origin + pages.path(id, language) + '"/>').join('\n') + '\n' +
      images.map(image => '    <image:image><image:loc>' + escape(pages.origin + image) + '</image:loc></image:image>').join('\n') + '\n  </url>');
  }
}
const projectBlock = start + '\n' + entries.join('\n') + '\n' + end;
sitemap = sitemap.includes(start) ? sitemap.replace(new RegExp(start + '[\\s\\S]*?' + end), projectBlock)
  : sitemap.replace('</urlset>', projectBlock + '\n</urlset>');
outputs.set('sitemap.xml', sitemap);
outputs.set(manifestFile, JSON.stringify(manifest, null, 2) + '\n');

const obsolete = Object.keys(previous.pages).filter(file => !outputs.has(file));
for (const file of [...Object.keys(manifest.pages), ...obsolete]) {
  if (!/^projects\/[a-z0-9-]+\/(?:fr\/)?index\.html$/.test(file)) throw new Error('Unsafe generated path');
  if (fs.existsSync(path.join(root, file)) && !read(file).includes(marker)) throw new Error('Refusing to overwrite a hand-written page: ' + file);
}
const changed = [...outputs].filter(([file, content]) => !fs.existsSync(path.join(root, file)) || read(file) !== content);
if (process.argv.includes('--check')) {
  if (changed.length || obsolete.some(file => fs.existsSync(path.join(root, file)))) throw new Error('Generated pages are stale. Run node tools/build-projects.cjs.');
} else {
  for (const [file, content] of changed) {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    fs.writeFileSync(path.join(root, file), content, 'utf8');
  }
  // Remove only builder-owned HTML when a project is hidden, protected or removed; never its media.
  for (const file of obsolete) if (fs.existsSync(path.join(root, file))) fs.unlinkSync(path.join(root, file));
}
console.log((process.argv.includes('--check') ? 'Verified ' : 'Built ') + ids.length * 2 + ' public project pages (EN/FR); protected and hidden projects excluded.');
